package com.ssmt.cli;

import static org.assertj.core.api.Assertions.assertThat;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import picocli.CommandLine;

/**
 * Cross-repo contract (Project Go H3, BridgeForge ROADMAP-3 80.9): the manifest this producer exports for the committed
 * fixture mod equals the committed golden file, which BridgeForge's CI imports with its real consumer. A producer change
 * that alters the export fails here until the golden is regenerated, and the regenerated bytes are then what BridgeForge
 * must accept.
 */
class CoverageManifestContractTest {
    private static final Path FIXTURE = Path.of("../fixtures/coverage-manifest");

    @TempDir Path directory;

    @Test void exportedManifestEqualsCommittedGolden() throws Exception {
        Path produced = directory.resolve("localization-coverage.json");
        int exit = new CommandLine(new Main()).execute("assess", FIXTURE.resolve("mod").toString(),
                "--coverage", "--coverage-manifest", produced.toString());
        assertThat(exit).isZero();
        String actual = Files.readString(produced, StandardCharsets.UTF_8).replace("\r\n", "\n");
        String golden = Files.readString(FIXTURE.resolve("localization-coverage.json"), StandardCharsets.UTF_8);
        assertThat(actual)
                .as("Regenerate with: ssmt-cli assess fixtures/coverage-manifest/mod --coverage "
                        + "--coverage-manifest fixtures/coverage-manifest/localization-coverage.json "
                        + "(then convert line endings to LF) and check BridgeForge still accepts it")
                .isEqualTo(golden);
    }
}
